export const CINEMATIC_PREVIEW_FOLDER = "GlassHorizonCinematicAssets";
export const CINEMATIC_PREVIEW_VERSION = 1;

export type CinematicPreviewAsset = "Kestrel" | "Vanta" | "Relay" | "Carrier";

export const CINEMATIC_PREVIEW_ASSETS: readonly CinematicPreviewAsset[] = [
	"Kestrel",
	"Vanta",
	"Relay",
	"Carrier",
];

const expectedGeometry: Record<CinematicPreviewAsset, string> = {
	Kestrel: "Kestrel",
	Vanta: "Vanta",
	Relay: "Relay",
	Carrier: "Carrier",
};

function hasVisibleGeometry(model: Model): boolean {
	for (const item of model.GetDescendants()) {
		if (item.IsA("BasePart") && item.Transparency < 1) return true;
	}
	return false;
}

/**
 * Resolves a complete server-published static preview. The client side of this
 * module is deliberately clone-only and never imports AssetService.
 */
export function findCinematicPreview(root: Instance, asset: CinematicPreviewAsset): Model | undefined {
	const folder = root.FindFirstChild(CINEMATIC_PREVIEW_FOLDER);
	if (
		!folder?.IsA("Folder") ||
		folder.GetAttribute("PreviewVersion") !== CINEMATIC_PREVIEW_VERSION ||
		folder.GetAttribute("Ready") !== true
	) return undefined;
	const candidate = folder.FindFirstChild(asset);
	if (
		!candidate?.IsA("Model") ||
		candidate.PrimaryPart === undefined ||
		candidate.GetAttribute("PreviewAsset") !== asset ||
		candidate.GetAttribute("GeometryAsset") !== expectedGeometry[asset]
	) return undefined;
	const geometrySource = candidate.GetAttribute("GeometrySource");
	if (geometrySource !== "Blender" && geometrySource !== "Fallback") return undefined;
	if (!hasVisibleGeometry(candidate)) return undefined;
	return candidate;
}

/** Clone-only client operation; authored/fallback geometry is generated by the server. */
export function cloneCinematicPreview(
	root: Instance,
	asset: CinematicPreviewAsset,
	parent: Instance,
	pivot: CFrame,
	scale = 1,
): Model | undefined {
	const source = findCinematicPreview(root, asset);
	if (!source) return undefined;
	const clone = source.Clone();
	clone.Name = `Cinematic${asset}`;
	clone.ScaleTo(scale);
	clone.PivotTo(pivot);
	for (const item of clone.GetDescendants()) {
		if (item.IsA("BasePart")) {
			item.Anchored = true;
			item.CanCollide = false;
			item.CanTouch = false;
			item.CanQuery = false;
		} else if (item.IsA("Trail") || item.IsA("ParticleEmitter") || item.IsA("Beam")) {
			item.Enabled = false;
		}
	}
	clone.Parent = parent;
	return clone;
}

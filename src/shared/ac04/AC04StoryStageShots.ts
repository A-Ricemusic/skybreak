/** Explicit compositions for the existing 48 original adaptation beats. Coordinates are stage-local studs.
 * No elapsed-time animation: seeking/back/replay reconstruct exactly the same observed moment.
 * `keys` name parts that must stay unoccluded and inside the frame (verified natively by raycast tests);
 * a `/Face` key additionally requires the camera to be in front of that actor's face. */
import { V } from "./AC04StoryStageGeometry";
export type StoryPerson = "boy" | "uncle" | "thirteen" | "four" | "daughter" | "barkeeper" | "pilot" | "recruit" | "mechanic" | "soldier" | "writer" | "citizen";
export type StoryPose = "watch" | "sit" | "play" | "offer" | "listen" | "guard" | "leave" | "kneel" | "write" | "hold" | "point" | "climb" | "sing" | "rest";
export type StoryMood = "neutral" | "smile" | "sad" | "stern" | "open";
export type StoryHeld = "guitar" | "harmonica" | "cloth" | "schoolbag" | "satchel" | "report" | "rifle" | "cup" | "pen" | "notes" | "plate" | "helmet" | "headphones" | "sling" | "torch" | "plank" | "armband";
export interface StoryActor {
	person: StoryPerson; at: V; toward: V; pose: StoryPose;
	look?: V; mood?: StoryMood; holds?: StoryHeld[]; seated?: boolean;
	/** World-space targets for hands; arms are solved toward them so contact is physical, not implied. */
	reach?: V; reachLeft?: V; variant?: number;
	/** Share (0..1) of a film-style cheat that turns body and head toward the camera; 0 keeps a deliberate back view. */
	cheat?: number;
}
export interface StoryProp { key: string; at: V; yaw: number; scale: number; }
export type StorySet = "cape" | "street" | "bar" | "runway" | "upstairs" | "damage" | "door" | "square" | "grave" | "overlook" | "desk";
export type StoryLight = "day" | "dusk" | "dawn" | "interior" | "attic" | "blackout" | "birch" | "study";
export interface StoryShot { subject: string; set: StorySet; light: StoryLight; eye: V; focus: V; fov: number; actors: StoryActor[]; props: StoryProp[]; keys: string[]; }
type Options = Partial<Omit<StoryActor, "person" | "at" | "toward" | "pose">>;
function a(person: StoryPerson, x: number, z: number, pose: StoryPose, tx: number, tz: number, options: Options = {}): StoryActor {
	return { person, at: [x, 0, z], toward: [tx, 3, tz], pose, ...options };
}
function p(key: string, x: number, y: number, z: number, yaw = 0, scale = 1): StoryProp { return { key, at: [x, y, z], yaw, scale }; }
function s(subject: string, set: StorySet, light: StoryLight, eye: V, focus: V, fov: number, actors: StoryActor[], props: StoryProp[], keys: string[]): StoryShot {
	return { subject, set, light, eye, focus, fov, actors, props, keys };
}

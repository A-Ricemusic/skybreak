#!/usr/bin/env python3
"""Isolated AC04 adapter for the existing cached voice generation/inspection pipeline.

No upload command. Existing assets/voice and shared VoiceCues/VoiceBanks are never
written. Run the offline transcript exporter before plan/generate/pack. Network
commands still require an explicit private --key-file and generation budget.
"""
import json
import subprocess
import voice

OUTPUT = voice.ROOT / "src/shared/ac04"


def write_cues(plan, all_lines):
    by_id = {line["id"]: line for line in all_lines}
    rows = ['// Generated by tools/ac04-voice.py pack; exact original AC04 scripts only.',
            'import { VoiceCue } from "../VoiceCues";',
            'export const AC04_VOICE_CUES: Record<string, VoiceCue> = {']
    for bank in plan["banks"]:
        for member in bank["members"]:
            line = by_id[member["id"]]
            cue = {"bank": "ac04_" + bank["id"], "start": member["start"], "finish": member["end"],
                   "speaker": line["speaker"], "tape": line["tape"], "radio": line["kind"] == "radio", "text": line["text"]}
            rows.append(f'\t{json.dumps(line["id"])}: {json.dumps(cue, ensure_ascii=False)},')
    rows.append('};\n')
    (OUTPUT / "AC04VoiceCues.ts").write_text("\n".join(rows))


def write_banks(plan, uploaded):
    # Packing never approves audio. Require both current independent review and
    # a matching moderation-approved record produced by a future upload adapter.
    review_record = voice.load_json(voice.VOICE / "review.json", {"banks": {}})
    reviews = review_record.get("banks", {})
    rows = ['// Generated by tools/ac04-voice.py pack. Empty IDs keep captions silent.',
            'export const AC04_VOICE_BANK_ASSETS: Record<string, string> = {']
    for bank in plan["banks"]:
        item, review = uploaded.get(bank["id"], {}), reviews.get(bank["id"], {})
        transcript = review.get("transcriptMatch", {})
        approved = (item.get("state") == "MODERATION_STATE_APPROVED" and item.get("sha256") == bank["sha256"]
                    and item.get("assetId") and review.get("approved") is True
                    and review.get("sha256") == bank["sha256"] and review.get("reviewer")
                    and review.get("method") and review_record.get("commercialUsePermitted") is True
                    and transcript.get("engine") and isinstance(transcript.get("minRate"), (int, float))
                    and transcript["minRate"] >= 0.9 and transcript.get("flagged") == [])
        asset = "rbxassetid://" + str(item["assetId"]) if approved else ""
        rows.append(f'\t{json.dumps("ac04_" + bank["id"])}: {json.dumps(asset)},')
    rows.append('};\n')
    (OUTPUT / "AC04VoiceBanks.ts").write_text("\n".join(rows))


if __name__ == "__main__":
    voice.VOICE = voice.ROOT / "assets/ac04-voice"
    subprocess.run(["bun", "tools/ac04-voice-lines.ts", "--check"], cwd=voice.ROOT, check=True)
    voice.write_cue_table = write_cues
    voice.write_bank_assets = write_banks
    voice.main()
